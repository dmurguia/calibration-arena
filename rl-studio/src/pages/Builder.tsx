const REAL_ONLY_REPLY = 'Done — 812 tasks, all replayed from production claims where an analyst confirmed or overrode the decision (PII scrubbed, VINs hashed). No synthetic cases, so rare edges like coverage boundaries and commercial use are thin — experts can author those.\n\nI held out 15% as a test split, stratified by vehicle line so F-150 doesn’t dominate.'

const ENV_YAML_FOR = (synthetic: number) => ENV_YAML.replace('synthetic: 428', `synthetic: ${synthetic}`)

const GRADER = (leak: boolean) => `# grader.py — generated, editable
from calibrated.grading import check, judge, penalty

def reward(task, traj):
    d = traj.final_decision
    r  = 0.35 * check(d.action == task.key.action)
    r += 0.20 * check(d.labor_op == task.key.labor_op and abs(d.hours - task.key.hours) <= 0.2)
    r += 0.15 * check(set(d.cited_bulletins) >= set(task.key.bulletins))
    r += 0.20 * judge("dealer_note", d.note, rubric=task.rubric, calibrated_on="ford-analysts-v2")
    r += 0.10 * check(traj.num_tool_calls <= 8)
${leak ? `    if d.action == "approve" and not task.key.in_coverage:
        return penalty(-1.0, "out_of_coverage_approval")   # ~$1,180 avg leakage
    if d.action == "escalate" and task.key.action != "escalate":
        r -= 0.03                                          # ~$38 analyst time` : `    if d.action == "approve" and not task.key.in_coverage:
        r -= 0.25`}
    if hallucinated_parts(d.note):
        r -= 0.5
    return r`

export default function Builder() {
  const { s, set, now } = useDemo()
  const [tab, setTab] = useState<'overview' | 'tools' | 'tasks' | 'reward' | 'files'>('overview')
  const [draft, setDraft] = useState('')
  const [pending, setPending] = useState(false)
  const [typed, setTyped] = useState<Record<number, string>>({})
  const endRef = useRef<HTMLDivElement>(null)
  const step = s.builderStep
  const vp = progressOf(s.validateStartedAt, DEMO_SPEED.validateMs, now)
  const checksDone = Math.floor(vp * CHECKS.length + 0.001)

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: 'smooth', block: 'end' })
  }, [step, pending])

  const send = (text: string) => {
    if (step >= SCRIPT.length || pending) return
    setTyped({ ...typed, [step]: text })
    setDraft('')
    setPending(true)
    setTimeout(() => {
      setPending(false)
      const next = step + 1
      set({ builderStep: next, ...(step === 1 ? { taskMix: /real claims|no synthetic|only real/i.test(text) ? 'real' : 'mixed' } : {}), ...(step === 3 ? { leakageWeighted: !/equal/i.test(text) } : {}) })
      setTab(next === 1 ? 'tools' : next === 2 ? 'tasks' : next >= 3 ? 'reward' : 'overview')
    }, 1600)
  }

  const current = SCRIPT[step]
  const tc = taskCounts(s)

  return (
    <>
      <PageHeader
        eyebrow="Learn · Environment"
        title="Vibe-build your RL environment"
        desc="Describe the job. Studio drafts the sandbox, tools, tasks and reward from your traces and APIs — you review it like a pull request."
        actions={
          vp >= 1 ? (
            <Link to="/app/experts"><Button>Next: add experts <ArrowRight size={14} /></Button></Link>
          ) : (
            <Button disabled={step < 4 || !!s.validateStartedAt} onClick={() => set({ validateStartedAt: Date.now() })}>
              {s.validateStartedAt ? <><Loader2 size={14} className="animate-spin" /> Validating…</> : 'Validate environment'}
            </Button>
          )
        }
      />

      <div className="grid h-[calc(100vh-210px)] min-h-[560px] grid-cols-[440px_1fr] gap-5">
        <Card pad={false} className="flex flex-col overflow-hidden">
          <div className="flex items-center gap-2 border-b border-hairline px-4 py-2.5 text-[13px] font-medium">
            <Sparkles size={14} className="text-leather" /> Environment copilot
          </div>
          <div className="scrollbar-thin flex-1 space-y-4 overflow-y-auto p-4">
            <div className="rounded-lg bg-paper p-3 text-[13px] leading-relaxed text-graphite">
              I’ll help you build an environment for <span className="font-mono text-ink">warranty-triage-agent</span>. Tell me what the agent should get better at, in your own words.
            </div>
            {SCRIPT.slice(0, step).map((m, i) => (
              <div key={i} className="space-y-3">
                <div className="ml-10 rounded-lg bg-ink px-3 py-2 text-[13px] leading-relaxed text-paper">{typed[i] ?? m.user}</div>
                <div className="whitespace-pre-line rounded-lg border border-hairline p-3 text-[13px] leading-relaxed">{(i === 1 && s.taskMix === 'real' ? REAL_ONLY_REPLY : m.reply).replace(/`/g, '')}</div>
              </div>
            ))}
            {pending && current && (
              <div className="space-y-3">
                <div className="ml-10 rounded-lg bg-ink px-3 py-2 text-[13px] leading-relaxed text-paper">{typed[step]}</div>
                <div className="flex items-center gap-2 text-[12.5px] text-graphite"><Loader2 size={13} className="animate-spin" /> {current.thinking}</div>
              </div>
            )}
            {step >= SCRIPT.length && (
              <div className="rounded-lg border border-good/30 bg-good-tint/60 p-3 text-[13px]">
                {vp >= 1 ? 'Validation passed. Next, bring in experts to author hard cases and calibrate the grader.' : s.validateStartedAt ? 'Validating…' : 'Click “Validate environment” to run the checks.'}
              </div>
            )}
            <div ref={endRef} />
          </div>
          <div className="border-t border-hairline p-3">
            {current && !pending && (
              <div className="mb-2 flex flex-col gap-1.5">
                {current.chips.map((c) => (
                  <button key={c} onClick={() => send(c)} className="rounded-md border border-hairline bg-paper px-2.5 py-1.5 text-left text-[12px] leading-snug text-graphite hover:border-ink/40 hover:text-ink">
                    {c}
                  </button>
                ))}
              </div>
            )}
            <form onSubmit={(e) => { e.preventDefault(); if (draft.trim()) send(draft.trim()) }} className="flex items-center gap-2">
              <input value={draft} onChange={(e) => setDraft(e.target.value)} disabled={!current || pending} placeholder={current ? 'Describe what good looks like…' : 'Environment drafted'} className="h-9 flex-1 rounded-md border border-hairline bg-card px-3 text-[13px] outline-none focus:border-ink disabled:bg-paper" />
              <Button type="submit" size="sm" disabled={!current || pending || !draft.trim()} className="h-9 w-9 px-0"><ArrowUp size={15} /></Button>
            </form>
          </div>
        </Card>

        <Card pad={false} className="flex flex-col overflow-hidden">
          <div className="flex items-center justify-between px-4 pt-3">
            <div>
              <div className="font-mono text-[13px]">ford-warranty-triage <span className="text-steel">v{Math.max(1, step)}</span></div>
              <div className="text-[12px] text-graphite">{step === 0 ? 'Empty — start in the chat' : vp >= 1 ? 'Validated · ready to train' : 'Draft'}</div>
            </div>
            {vp >= 1 ? <Badge tone="good"><Check size={11} /> Validated</Badge> : <Badge>Draft</Badge>}
          </div>
          <div className="px-4 pt-2">
            <Tabs value={tab} onChange={setTab} tabs={[{ id: 'overview', label: 'Overview' }, { id: 'tools', label: `Tools${step >= 1 ? ' · 7' : ''}` }, { id: 'tasks', label: `Tasks${step >= 2 ? ` · ${tc.total.toLocaleString()}` : ''}` }, { id: 'reward', label: 'Reward' }, { id: 'files', label: 'Files' }]} />
          </div>
          <div className="scrollbar-thin flex-1 overflow-y-auto p-4">
            {tab === 'overview' && (
              <div className="space-y-4">
                <div className="grid grid-cols-4 gap-3">
                  {[['Tools', step >= 1 ? '7' : '—'], ['Tasks', step >= 2 ? tc.total.toLocaleString() : '—'], ['Reward terms', step >= 3 ? '7' : '—'], ['Validation', vp >= 1 ? '6/6' : s.validateStartedAt ? `${checksDone}/6` : '—']].map(([k, v]) => (
                    <div key={k} className="rounded-md bg-paper p-3">
                      <div className="text-[11.5px] text-graphite">{k}</div>
                      <div className="font-mono text-[18px]">{v}</div>
                    </div>
                  ))}
                </div>
                <div>
                  <div className="mb-2 text-[12.5px] font-medium text-graphite">How an episode works</div>
                  <div className="flex items-center gap-2 text-[12.5px]">
                    {['Dealer claim', 'Agent calls tools', 'submit_decision', 'Grader scores', 'Reward → RL update'].map((x, i, a) => (
                      <div key={x} className="flex items-center gap-2">
                        <span className={cx('rounded-md border px-2.5 py-1.5', step > i || step >= 3 ? 'border-ink/30 bg-card' : 'border-dashed border-hairline text-steel')}>{x}</span>
                        {i < a.length - 1 && <ArrowRight size={12} className="text-steel" />}
                      </div>
                    ))}
                  </div>
                </div>
                {s.validateStartedAt && (
                  <div>
                    <div className="mb-2 text-[12.5px] font-medium text-graphite">Validation</div>
                    <div className="space-y-1.5">
                      {CHECKS.map(([t, d], i) => (
                        <div key={t} className="flex items-start gap-2.5 rounded-md border border-hairline px-3 py-2">
                          {i < checksDone ? <Check size={15} className="mt-0.5 text-good" /> : i === checksDone ? <Loader2 size={15} className="mt-0.5 animate-spin text-leather" /> : <Circle size={15} className="mt-0.5 text-steel" />}
                          <div>
                            <div className="text-[13px] font-medium">{t}</div>
                            {i < checksDone && <div className="text-[12px] text-graphite">{d}</div>}
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                )}
                {step === 0 && <div className="rounded-md border border-dashed border-hairline p-8 text-center text-[13px] text-graphite">Your environment will appear here as you describe it.</div>}
              </div>
            )}
            {tab === 'tools' && (step >= 1 ? (
              <div className="space-y-2">
                {ENV_TOOLS.map((t, i) => (
                  <div key={t.name} className="flex items-start gap-3 rounded-md border border-hairline px-3 py-2.5 animate-fadein" style={{ animationDelay: `${i * 60}ms` }}>
                    <Wrench size={14} className="mt-0.5 text-leather" />
                    <div className="flex-1">
                      <div className="flex items-center gap-2"><span className="font-mono text-[13px]">{t.name}</span>{(t.name === 'tsb_search' || t.name === 'labor_time_guide') && <Badge tone="leather">added</Badge>}</div>
                      <div className="text-[12.5px] text-graphite">{t.desc}</div>
                    </div>
                    <div className="text-right text-[11.5px] text-steel">{t.source}</div>
                  </div>
                ))}
              </div>
            ) : <Pending />)}
            {tab === 'tasks' && (step >= 2 ? (
              <div className="space-y-4">
                <div className="grid grid-cols-3 gap-3">
                  {[['Replayed from production', '812', 'analyst-confirmed answer keys'], ['Synthetic hard cases', tc.synthetic ? String(tc.synthetic) : 'off', tc.synthetic ? 'TSB, coverage-edge, commercial use' : 'real claims only'], ['Expert-authored', s.expertOrder ? '300' : 'pending', s.expertOrder ? 'from Calibrated experts' : 'add experts →']].map(([k, v, d]) => (
                    <div key={k} className="rounded-md bg-paper p-3">
                      <div className="text-[11.5px] text-graphite">{k}</div>
                      <div className="font-mono text-[18px]">{v}</div>
                      <div className="text-[11.5px] text-steel">{d}</div>
                    </div>
                  ))}
                </div>
                <table className="w-full text-[12.5px]">
                  <thead><tr className="border-b border-hairline text-left text-[11px] uppercase tracking-wider text-graphite"><th className="py-2 font-medium">Task</th><th className="font-medium">Source</th><th className="font-medium">Answer key</th><th className="font-medium">Split</th></tr></thead>
                  <tbody>
                    {[
                      ['F-150 3.5L cold-start rattle, P0016', 'replay', 'Adjust → 12-6500-B 8.4 h, TSB 26-2141', 'train'],
                      ['F-250 6.7L turbo actuator @ 63,410 mi', 'replay', 'Reject → outside powertrain 5yr/60k', 'test'],
                      ['Ranger 2.3L front pads @ 18k mi', 'replay', 'Approve → wear item within B2B, no escalation', 'train'],
                      ['Explorer Hybrid HV coolant pump', 'synthetic', 'Approve → hybrid unique 8yr/100k', 'train'],
                      ['Transit fleet van, commercial use, 38k mi', 'synthetic', 'Request info → commercial coverage terms', 'test'],
                      ['Edge 2.0L A/C, invented part in RO', 'synthetic', 'Request info → part not in catalog', 'train'],
                    ].filter((r) => tc.synthetic || r[1] !== 'synthetic').map((r) => (
                      <tr key={r[0]} className="border-b border-hairline last:border-0">
                        <td className="py-2">{r[0]}</td>
                        <td><Badge tone={r[1] === 'replay' ? 'neutral' : 'leather'}>{r[1]}</Badge></td>
                        <td className="text-graphite">{r[2]}</td>
                        <td className="font-mono text-[11.5px]">{r[3]}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            ) : <Pending />)}
            {tab === 'reward' && (step >= 3 ? (
              <div className="space-y-2">
                {REWARD_TERMS.map((t) => {
                  const w = t.id === 'leak' ? (s.leakageWeighted ? 'floor' : '−0.25') : t.weight
                  return (
                    <div key={t.id} className="flex items-center gap-3 rounded-md border border-hairline px-3 py-2.5">
                      <Badge tone={t.kind === 'penalty' ? 'bad' : t.kind === 'rubric' ? 'leather' : 'neutral'}>{t.kind}</Badge>
                      <div className="flex-1">
                        <div className="text-[13px] font-medium">{t.label}</div>
                        <div className="text-[12px] text-graphite">{t.how}</div>
                      </div>
                      <div className={cx('font-mono text-[13px]', t.kind === 'penalty' && 'text-bad')}>{typeof w === 'number' ? (w > 0 ? `+${w.toFixed(2)}` : w.toFixed(2)) : w}</div>
                    </div>
                  )
                })}
                {step >= 4 && <div className="rounded-md bg-leather-tint/60 p-3 text-[12.5px] text-ink">{s.leakageWeighted ? 'Weighted by business cost: a wrong approval (~$1,180) floors the reward; an unneeded escalation (~$38) costs −0.03.' : 'Wrong approvals and escalations weighted equally.'}</div>}
              </div>
            ) : <Pending />)}
            {tab === 'files' && (step >= 1 ? (
              <div className="space-y-3">
                <Code title="environment.yaml" code={ENV_YAML_FOR(tc.synthetic)} />
                {step >= 3 && <Code title="grader.py" code={GRADER(s.leakageWeighted)} />}
              </div>
            ) : <Pending />)}
          </div>
        </Card>
      </div>
    </>
  )
}

function Pending() {
  return <div className="rounded-md border border-dashed border-hairline p-8 text-center text-[13px] text-graphite">Not drafted yet — keep going in the chat.</div>
}
